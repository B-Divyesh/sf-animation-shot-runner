import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {resolve} from 'node:path';
import {setTimeout as delay} from 'node:timers/promises';
import {chromium} from 'playwright';

const port = 4174;
const localOrigin = `http://127.0.0.1:${port}`;
const origin = (process.env.TEST_URL || localOrigin).replace(/\/$/, '');
const vite = process.env.TEST_URL ? null : spawn(process.execPath, [
  resolve('node_modules/vite/bin/vite.js'),
  'preview',
  '--config', 'site/vite.config.js',
  '--host', '127.0.0.1',
  '--port', String(port),
  '--strictPort',
], {stdio: 'ignore'});
const viteExited = vite && once(vite, 'exit');

async function waitForServer() {
  for (let attempt = 0; attempt < 50; attempt += 1) {
    try {
      const response = await fetch(origin);
      if (response.ok) return;
    } catch {}
    await delay(100);
  }
  throw new Error('Vite preview did not start');
}

try {
  await waitForServer();
  const browser = await chromium.launch({headless: true});
  const context = await browser.newContext();
  // Keep the regression offline from the real billing service while exercising
  // the exact browser request generated by a returned license token.
  await context.route('https://api.sociobot.in/**', route => route.fulfill({
    contentType: 'application/json',
    headers: {'access-control-allow-origin': origin},
    body: JSON.stringify({valid: false, reason: 'invalid'}),
  }));
  const page = await context.newPage();
  await page.goto(`${origin}/`, {waitUntil: 'networkidle'});
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.reload({waitUntil: 'networkidle'});
  assert.equal(await page.evaluate(() => Boolean(navigator.serviceWorker.controller)), true, 'service worker controls the page');

  await page.goto(`${origin}/?license=browser-security-probe`, {waitUntil: 'networkidle'});
  await page.waitForFunction(() => !location.search);
  await page.evaluate(() => fetch('/verify?license=verification-response-probe').catch(() => undefined));

  const cachedUrls = await page.evaluate(async () => {
    const names = await caches.keys();
    const keys = await Promise.all(names.map(async name => {
      const cache = await caches.open(name);
      return (await cache.keys()).map(request => request.url);
    }));
    return keys.flat();
  });
  assert.equal(
    cachedUrls.some(url => /license|token|entitlement|\/verify/i.test(url)),
    false,
    `Cache Storage retained a sensitive URL: ${cachedUrls.join(', ')}`,
  );
  assert.equal(
    cachedUrls.some(url => url.startsWith('https://api.sociobot.in/')),
    false,
    'Cache Storage retained a Sociobot entitlement response',
  );
  await browser.close();
  console.log('PWA license-cache security regression passed');
} finally {
  vite?.kill('SIGTERM');
  await viteExited?.catch(() => {});
}
